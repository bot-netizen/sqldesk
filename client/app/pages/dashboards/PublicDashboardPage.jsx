import React from "react";
import PropTypes from "prop-types";

import PageHeader from "@/components/PageHeader";
import DashboardGrid from "@/components/dashboards/DashboardGrid";

import { Dashboard } from "@/services/dashboard";

import useDashboard from "./hooks/useDashboard";
import LiveBadge from "./components/LiveBadge";
import DashboardFilters from "./components/DashboardFilters";

import useScreenshotMode, { everyWidgetHasFinished, inScreenshotMode } from "@/lib/hooks/useScreenshotMode";
import ScreenshotFrame, { generatedAt } from "@/components/ScreenshotFrame";
import { capitalizeFirst } from "@/lib/utils";

import "./PublicDashboardPage.less";
import Spinner from "@/components/Spinner";

/*
  Each table in the order the person it is drawn for last saw it in, by widget
  id. Sorting by a column header happens in the browser alone, so a picture
  drawn here showed the query's order where their Export as image showed
  theirs. The table starts from `sortBy` (viz-lib's table `savedOrder`).
*/
export function applyTableOrders(widgets, orders) {
  if (!orders) {
    return;
  }
  (widgets || []).forEach((widget) => {
    const order = orders[String(widget.id)];
    // Once: the page renders many times while its widgets load, and a new
    // options object each time would redraw every table for nothing.
    const visualization = widget.visualization;
    if (order && visualization && visualization.type === "TABLE" && visualization.options?.sortBy !== order) {
      visualization.options = { ...visualization.options, sortBy: order };
    }
  });
}

function PublicDashboard({ dashboard, token }) {
  const dashboardConfiguration = useDashboard(dashboard, { publicToken: token });
  const { filters, loadWidget, refreshWidget, live } = dashboardConfiguration;

  // Being photographed for an alert: say so once every widget has something
  // to show, or the renderer captures a page of spinners -- or, as it turned
  // out, a page of nothing at all.
  useScreenshotMode(everyWidgetHasFinished(dashboard.widgets));

  // Photographed for Slack, an email or an alert: on the same branded page
  // Export as image draws, rather than the bare grid edge to edge. No filters
  // and no live badge -- a picture cannot be clicked -- and the name moves
  // into the frame's band.
  if (inScreenshotMode()) {
    // The same three fields Export as image writes. Owner and sender come
    // only with a render pass (`picture`); a public link never names anyone.
    const picture = dashboard.picture || {};
    applyTableOrders(dashboard.widgets, picture.table_orders);
    const fields = [
      { label: "Owner", value: picture.owner },
      { label: "Generated by", value: picture.generated_by },
      { label: "Generated at", value: generatedAt() },
    ];
    return (
      <ScreenshotFrame title={capitalizeFirst(dashboard.name)} fields={fields}>
        <div id="dashboard-container">
          <DashboardGrid
            dashboard={dashboard}
            widgets={dashboard.widgets}
            filters={filters}
            isEditing={false}
            isPublic
            isLive={false}
            liveInterval={null}
            onLoadWidget={loadWidget}
            onRefreshWidget={refreshWidget}
          />
        </div>
      </ScreenshotFrame>
    );
  }

  return (
    <div className="container p-t-10 p-b-20">
      {/*
        Beside the title rather than in a band of its own above the grid --
        the same control the signed-in page puts beside Refresh. A shared
        dashboard is the one most likely to be read on a laptop in a meeting,
        so the row it used to spend on one dropdown is the row worth having.
      */}
      <PageHeader
        title={dashboard.name}
        actions={
          <span className="public-dashboard-actions">
            {live ? <LiveBadge live={live} /> : null}
            <DashboardFilters dashboardConfiguration={dashboardConfiguration} />
          </span>
        }
      />
      <div id="dashboard-container">
        <DashboardGrid
          dashboard={dashboard}
          widgets={dashboard.widgets}
          filters={filters}
          isEditing={false}
          isPublic
          isLive={!!live}
          liveInterval={live && !live.paused ? live.interval : null}
          onLoadWidget={loadWidget}
          onRefreshWidget={refreshWidget}
        />
      </div>
    </div>
  );
}

PublicDashboard.propTypes = {
  dashboard: PropTypes.object.isRequired, // eslint-disable-line react/forbid-prop-types
  token: PropTypes.string.isRequired,
};

class PublicDashboardPage extends React.Component {
  static propTypes = {
    token: PropTypes.string.isRequired,
    onError: PropTypes.func,
  };

  static defaultProps = {
    onError: () => {},
  };

  state = {
    loading: true,
    dashboard: null,
  };

  componentDidMount() {
    Dashboard.getByToken({ token: this.props.token })
      .then((dashboard) => this.setState({ dashboard, loading: false }))
      .catch((error) => this.props.onError(error));
  }

  render() {
    const { loading, dashboard } = this.state;
    return (
      <div className="public-dashboard-page">
        {loading ? (
          <div className="container loading-message text-center" role="status" aria-live="polite">
            <Spinner size="large" />
            <div className="m-t-15">Loading...</div>
          </div>
        ) : (
          <PublicDashboard dashboard={dashboard} token={this.props.token} />
        )}
      </div>
    );
  }
}

export default PublicDashboardPage;
